#!/usr/bin/env python3
"""Generate standalone site palettes and project logos from shared brand sources."""
import argparse
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
CONF = ROOT / 'conf'
PALETTE = json.loads((CONF / 'palette.json').read_text())
CSS = '/* Generated by conf/sync_palette.py; edit conf/palette.json. */\n:root {\n'
CSS += '  color-scheme: dark;\n'
CSS += ''.join(f'  --{key}: {value};\n' for key, value in PALETTE.items())
CSS += '}\n'
TARGETS = ['src/gw_piano/web/theme.css']
LOGOS = {
    'gw-piano-dark.svg': ['src/gw_piano/web/gw-piano-dark.svg'],
    'chirp-lab.svg': ['src/gw_piano/web/chirp-lab.svg'],
}


def outputs():
    for target in TARGETS:
        yield ROOT / target, CSS
    for template, targets in LOGOS.items():
        svg = (CONF / 'templates' / template).read_text()
        for key, value in PALETTE.items():
            svg = svg.replace('{{' + key + '}}', value)
        if '{{' in svg:
            raise ValueError(f'Unknown palette token in {template}')
        for target in targets:
            yield ROOT / target, svg
    for target in ['src/gw_piano/web/index.html']:
        path = ROOT / target
        yield path, re.sub(r'(<meta name="theme-color" content=")[^"]+',
                           lambda m: m[1] + PALETTE['bg'], path.read_text())


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='Fail if generated assets are out of date')
    args = parser.parse_args()
    stale = []
    for path, content in outputs():
        if not path.exists() or path.read_text() != content:
            stale.append(str(path.relative_to(ROOT)))
            if not args.check:
                path.write_text(content)
    if args.check and stale:
        parser.exit(1, 'Stale palette assets: ' + ', '.join(stale) + '\n')
    print('Palette assets verified.' if args.check else 'Palette assets synchronized.')


if __name__ == '__main__':
    main()
