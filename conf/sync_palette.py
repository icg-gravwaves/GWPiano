#!/usr/bin/env python3
"""Generate the site theme (colours and fonts) and project logos from conf/theme.json."""
import argparse
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
CONF = ROOT / 'conf'
THEME = json.loads((CONF / 'theme.json').read_text())
PALETTE = THEME['colours']
FONTS = THEME['fonts']
WEB = ROOT / 'src/gw_piano/web'


def theme_css():
    """CSS custom properties for every colour and font role, plus @font-face rules for the bundled files."""
    css = '/* Generated by conf/sync_palette.py; edit conf/theme.json. */\n'
    for font in FONTS.values():
        for weight, name in font['files'].items():
            css += (f"@font-face{{font-family:'{font['family']}';font-weight:{weight};"
                    f"font-display:swap;src:url({name}) format('truetype')}}\n")
    css += ':root {\n  color-scheme: dark;\n'
    css += ''.join(f'  --{key}: {value};\n' for key, value in PALETTE.items())
    for role, font in FONTS.items():
        css += f"  --font-{role}: '{font['family']}', sans-serif;\n  --weight-{role}: {font['weight']};\n"
    return css + '}\n'


TARGETS = ['src/gw_piano/web/theme.css']
LOGOS = {
    'gw-piano-dark.svg': ['src/gw_piano/web/gw-piano-dark.svg'],
}


def outputs():
    for target in TARGETS:
        yield ROOT / target, theme_css()
    # Font files are served next to the pages that use them
    for font in FONTS.values():
        for name in font['files'].values():
            yield WEB / name, (CONF / 'fonts' / name).read_bytes()
    for template, targets in LOGOS.items():
        svg = (CONF / 'templates' / template).read_text()
        for key, value in PALETTE.items():
            svg = svg.replace('{{' + key + '}}', value)
        if '{{' in svg:
            raise ValueError(f'Unknown palette token in {template}')
        for target in targets:
            yield ROOT / target, svg
    for target in ['src/gw_piano/web/index.html']:
        path = ROOT / target
        yield path, re.sub(r'(<meta name="theme-color" content=")[^"]+',
                           lambda m: m[1] + PALETTE['bg'], path.read_text())


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='Fail if generated assets are out of date')
    args = parser.parse_args()
    stale = []
    for path, content in outputs():
        current = path.read_bytes() if path.exists() else None
        data = content if isinstance(content, bytes) else content.encode()
        if current != data:
            stale.append(str(path.relative_to(ROOT)))
            if not args.check:
                path.write_bytes(data)
    if args.check and stale:
        parser.exit(1, 'Stale theme assets: ' + ', '.join(stale) + '\n')
    print('Theme assets verified.' if args.check else 'Theme assets synchronized.')


if __name__ == '__main__':
    main()
